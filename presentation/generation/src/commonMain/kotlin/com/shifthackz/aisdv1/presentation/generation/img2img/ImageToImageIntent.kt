package com.shifthackz.aisdv1.presentation.generation.img2img

import com.shifthackz.aisdv1.core.mvi.MviIntent
import com.shifthackz.aisdv1.domain.entity.ADetailerConfig
import com.shifthackz.aisdv1.domain.entity.UpscalerConfiguration
import com.shifthackz.aisdv1.domain.entity.AiGenerationResult
import com.shifthackz.aisdv1.domain.entity.FalAiAcceleration
import com.shifthackz.aisdv1.domain.entity.FalAiImageSize
import com.shifthackz.aisdv1.domain.entity.FalAiModel
import com.shifthackz.aisdv1.domain.entity.OpenAiModel
import com.shifthackz.aisdv1.domain.entity.OpenAiQuality
import com.shifthackz.aisdv1.domain.entity.OpenAiSize
import com.shifthackz.aisdv1.domain.entity.Scheduler
import com.shifthackz.aisdv1.domain.entity.StabilityAiClipGuidance
import com.shifthackz.aisdv1.domain.entity.StabilityAiStylePreset
import com.shifthackz.aisdv1.presentation.generation.widget.input.GenerationAspectRatio

/**
 * User requests for image selection, image-to-image generation, prompt restoration and shared inpaint editing.
 *
 * @author Dmitriy Moroz
 */
sealed interface ImageToImageIntent : MviIntent {
    /**
     * Opens independent provider/model setup.
     *
     * @author Dmitriy Moroz
     */
    data object ConfigureUpscaler : ImageToImageIntent

    /**
     * Captures the selected input for the owning screen action.
     *
     * @param configuration Captured optional final-stage model.
     * @author Dmitriy Moroz
     */
    data class UpdateUpscaler(val configuration: UpscalerConfiguration?) : ImageToImageIntent

    /**
     * Retries an empty AUTOMATIC1111 sampler list after foregrounding or a user retry.
     *
     * @author Dmitriy Moroz
     */
    data object RetrySamplers : ImageToImageIntent


    data object OpenDrawer : ImageToImageIntent


    data object NavigateBack : ImageToImageIntent


    data object ConfigureProvider : ImageToImageIntent


    data object NavigateToInPaint : ImageToImageIntent


    data object PickCamera : ImageToImageIntent


    data object PickGallery : ImageToImageIntent


    data object PickRandom : ImageToImageIntent

    /**
     * Replaces only the source pixels, clearing masks and results tied to the old source.
     *
     * @param base64 Original output image selected from the in-app gallery.
     * @author Dmitriy Moroz
     */
    data class ApplyImageInput(val base64: String) : ImageToImageIntent


    data object ClearImageInput : ImageToImageIntent


    data object Generate : ImageToImageIntent


    data object RunBenchmarkFromPrompt : ImageToImageIntent


    data object SkipBenchmarkPrompt : ImageToImageIntent


    data object ContinueAfterBenchmarkWarning : ImageToImageIntent


    data object SuppressBenchmarkWarningAndContinue : ImageToImageIntent


    data object DismissModal : ImageToImageIntent


    data object CancelGeneration : ImageToImageIntent


    data object UndoInPaintStroke : ImageToImageIntent


    data object ClearInPaintMask : ImageToImageIntent


    data object DismissError : ImageToImageIntent


    data object DismissMessage : ImageToImageIntent


    data object DismissEditTag : ImageToImageIntent

    /**
     * Appends a completed gesture to the current inpaint mask.
     *
     * @param stroke Stroke points and brush geometry captured in the editor canvas coordinate space.
     *
     * @author Dmitriy Moroz
     */
    data class DrawInPaintStroke(val stroke: InPaintStroke) : ImageToImageIntent

    /**
     * Exports original generated bytes through the native media adapter.
     *
     * @param base64 Original encoded result image, not a sampled display preview.
     *
     * @author Dmitriy Moroz
     */
    data class SaveResult(val base64: String) : ImageToImageIntent

    /**
     * Hands original generated bytes to native sharing.
     *
     * @param base64 Original encoded result image, not a sampled display preview.
     *
     * @author Dmitriy Moroz
     */
    data class ShareResult(val base64: String) : ImageToImageIntent

    /**
     * Persists generated outputs that do not yet have durable gallery identities.
     *
     * @param results Completed generation records to save.
     *
     * @author Dmitriy Moroz
     */
    data class SaveGenerationResults(val results: List<AiGenerationResult>) : ImageToImageIntent

    /**
     * Opens a completed output in the gallery/detail flow.
     *
     * @param result Generation record whose image and metadata should be displayed.
     *
     * @author Dmitriy Moroz
     */
    data class ViewGenerationResult(val result: AiGenerationResult) : ImageToImageIntent

    /**
     * Opens reporting for a completed generation result.
     *
     * @param result Generation image and identity selected for reporting.
     *
     * @author Dmitriy Moroz
     */
    data class ReportGenerationResult(val result: AiGenerationResult) : ImageToImageIntent

    /**
     * Opens the prompt-tag editor with the current prompt pair.
     *
     * @param prompt Current positive prompt before tag editing.
     * @param negativePrompt Current negative prompt before tag editing.
     * @param tag Exact tag text selected for editing.
     * @param isNegative Whether the selected tag belongs to the negative prompt.
     *
     * @author Dmitriy Moroz
     */
    data class ShowEditTag(

        val prompt: String,

        val negativePrompt: String,

        val tag: String,

        val isNegative: Boolean,
    ) : ImageToImageIntent

    /**
     * Replaces both prompts after an external tag/extra editor confirms.
     *
     * @param prompt Confirmed positive prompt.
     * @param negativePrompt Confirmed negative prompt.
     *
     * @author Dmitriy Moroz
     */
    data class ApplyPrompts(

        val prompt: String,

        val negativePrompt: String,
    ) : ImageToImageIntent

    /**
     * Restores generation parameters and the selected original image from an existing result.
     *
     * @param ai Source generation metadata and image content.
     * @param inputImage Whether to restore the source input image instead of its output image.
     *
     * @author Dmitriy Moroz
     */
    data class ApplyGenerationResult(

        val ai: AiGenerationResult,

        val inputImage: Boolean = false,
    ) : ImageToImageIntent

    /**
     * Changes advanced-form expansion without submitting generation.
     *
     * @param visible Whether advanced controls should be rendered.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateAdvancedOptionsVisibility(val visible: Boolean) : ImageToImageIntent

    /**
     * Replaces the positive prompt text.
     *
     * @param value User-entered positive prompt.
     *
     * @author Dmitriy Moroz
     */
    data class UpdatePrompt(val value: String) : ImageToImageIntent

    /**
     * Replaces the negative prompt text.
     *
     * @param value User-entered negative prompt.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateNegativePrompt(val value: String) : ImageToImageIntent

    /**
     * Edits the output width before dimension validation.
     *
     * @param value Raw width text, including incomplete/invalid user edits.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateWidth(val value: String) : ImageToImageIntent


    data object SwapDimensions : ImageToImageIntent

    /**
     * Applies a preset output ratio using the current dimensions.
     *
     * @param ratio Ratio preset selected from the generation form.
     *
     * @author Dmitriy Moroz
     */
    data class ApplyAspectRatio(val ratio: GenerationAspectRatio) : ImageToImageIntent

    /**
     * Edits the output height before dimension validation.
     *
     * @param value Raw height text, including incomplete/invalid user edits.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateHeight(val value: String) : ImageToImageIntent

    /**
     * Changes the inference step count.
     *
     * @param value Requested sampling steps.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateSamplingSteps(val value: Int) : ImageToImageIntent

    /**
     * Changes classifier-free guidance strength.
     *
     * @param value Requested CFG scale.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateCfgScale(val value: Float) : ImageToImageIntent

    /**
     * Toggles face restoration for providers that support it.
     *
     * @param value Whether post-generation face restoration is enabled.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateRestoreFaces(val value: Boolean) : ImageToImageIntent

    /**
     * Edits the primary seed before provider-specific validation.
     *
     * @param value Raw seed text, including random-seed sentinel or incomplete edits.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateSeed(val value: String) : ImageToImageIntent

    /**
     * Edits the variation seed before provider-specific validation.
     *
     * @param value Raw subseed text.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateSubSeed(val value: String) : ImageToImageIntent

    /**
     * Changes interpolation strength for the variation seed.
     *
     * @param value Requested subseed influence.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateSubSeedStrength(val value: Float) : ImageToImageIntent

    /**
     * Selects a sampling method from the active provider catalog.
     *
     * @param value Provider sampler identifier.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateSampler(val value: String) : ImageToImageIntent

    /**
     * Selects the provider scheduler.
     *
     * @param value Scheduler token selected by the user.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateScheduler(val value: Scheduler) : ImageToImageIntent

    /**
     * Changes the provider content-safety preference.
     *
     * @param value Whether NSFW content is requested/allowed by the current form.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateNsfw(val value: Boolean) : ImageToImageIntent

    /**
     * Changes the requested output batch size.
     *
     * @param value Number of images requested by the form.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateBatchCount(val value: Int) : ImageToImageIntent

    /**
     * Selects the official OpenAI image model.
     *
     * @param value Chosen OpenAI model token.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateOpenAiModel(val value: OpenAiModel) : ImageToImageIntent

    /**
     * Selects an official OpenAI output size.
     *
     * @param value Chosen OpenAI size token.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateOpenAiSize(val value: OpenAiSize) : ImageToImageIntent

    /**
     * Selects official OpenAI quality.
     *
     * @param value Chosen quality token.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateOpenAiQuality(val value: OpenAiQuality) : ImageToImageIntent

    /**
     * Selects the Fal.ai model.
     *
     * @param value Chosen Fal.ai model token.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateFalAiModel(val value: FalAiModel) : ImageToImageIntent

    /**
     * Selects Fal.ai output dimensions.
     *
     * @param value Chosen Fal.ai image-size preset.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateFalAiImageSize(val value: FalAiImageSize) : ImageToImageIntent

    /**
     * Selects Fal.ai inference acceleration.
     *
     * @param value Chosen acceleration mode.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateFalAiAcceleration(val value: FalAiAcceleration) : ImageToImageIntent

    /**
     * Changes Fal.ai synchronous response handling.
     *
     * @param value Whether synchronous generation is requested.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateFalAiSyncMode(val value: Boolean) : ImageToImageIntent

    /**
     * Selects an ArliAI checkpoint.
     *
     * @param value Provider model identifier.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateArliAiModel(val value: String) : ImageToImageIntent

    /**
     * Selects a Stability AI style preset.
     *
     * @param value Chosen style token.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateStabilityAiStyle(val value: StabilityAiStylePreset) : ImageToImageIntent

    /**
     * Selects Stability AI CLIP guidance.
     *
     * @param value Chosen CLIP guidance token.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateStabilityAiClipGuidance(val value: StabilityAiClipGuidance) :
        ImageToImageIntent

    /**
     * Replaces the ADetailer extension configuration.
     *
     * @param value Captured extension settings for the next request.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateADetailerConfig(val value: ADetailerConfig) : ImageToImageIntent


    data object RefreshADetailerAvailability : ImageToImageIntent


    data object OpenADetailerInstallInstructions : ImageToImageIntent

    /**
     * Changes how strongly output may differ from the source image.
     *
     * @param value Requested denoising strength.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateDenoisingStrength(val value: Float) : ImageToImageIntent

    /**
     * Changes the inpaint brush diameter.
     *
     * @param value Brush size in the editor canvas coordinate system.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateInPaintBrushSize(val value: Int) : ImageToImageIntent

    /**
     * Changes inpaint mask feathering.
     *
     * @param value Mask blur amount in pixels.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateInPaintMaskBlur(val value: Int) : ImageToImageIntent

    /**
     * Changes context retained around an isolated mask region.
     *
     * @param value Padding around the masked area in pixels.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateInPaintOnlyMaskedPadding(val value: Int) : ImageToImageIntent

    /**
     * Selects whether masked or unmasked regions are regenerated.
     *
     * @param value Chosen mask interpretation.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateInPaintMaskMode(val value: ImageInPaintState.MaskMode) : ImageToImageIntent

    /**
     * Selects the initial content used inside the inpaint mask.
     *
     * @param value Chosen fill/original/latent initialization policy.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateInPaintMaskContent(val value: ImageInPaintState.MaskContent) :
        ImageToImageIntent

    /**
     * Selects full-image or mask-only inpaint processing.
     *
     * @param value Chosen inpaint processing area.
     *
     * @author Dmitriy Moroz
     */
    data class UpdateInPaintArea(val value: ImageInPaintState.Area) : ImageToImageIntent
}
