package com.shifthackz.aisdv1.data.mappers

import com.shifthackz.aisdv1.domain.entity.AiGenerationResult
import com.shifthackz.aisdv1.domain.entity.ImageToImagePayload
import com.shifthackz.aisdv1.domain.entity.TextToImagePayload
import com.shifthackz.aisdv1.network.request.HuggingFaceGenerationRequest

/**
 * Uses the text prompt as inference input and converts an explicit seed to its numeric wire value.
 * Blank, negative or nonnumeric seeds are omitted so the provider can choose a random seed.
 *
 * @author Dmitriy Moroz
 */
fun TextToImagePayload.mapToHuggingFaceRequest(): HuggingFaceGenerationRequest = with(this) {
    HuggingFaceGenerationRequest(
        inputs = prompt,
        parameters = HuggingFaceGenerationRequest.Parameters(
            width = width,
            height = height,
            negativePrompt = negativePrompt.trim().takeIf(String::isNotBlank),
            seed = seed.trim().toLongOrNull()?.takeIf { it >= 0L },
            numInferenceSteps = samplingSteps,
            guidanceScale = cfgScale,
        ),
    )
}

/**
 * Uses the source image as inference input and sends text guidance under the task's `prompt` key.
 * Blank, negative or nonnumeric seeds are omitted so the provider can choose a random seed.
 *
 * @author Dmitriy Moroz
 */
fun ImageToImagePayload.mapToHuggingFaceRequest(): HuggingFaceGenerationRequest = with(this) {
    HuggingFaceGenerationRequest(
        inputs = base64Image,
        parameters = HuggingFaceGenerationRequest.Parameters(
            width = width,
            height = height,
            prompt = prompt.trim().takeIf(String::isNotBlank),
            negativePrompt = negativePrompt.trim().takeIf(String::isNotBlank),
            seed = seed.trim().toLongOrNull()?.takeIf { it >= 0L },
            numInferenceSteps = samplingSteps,
            guidanceScale = cfgScale,
        ),
    )
}

/**
 * Combines a returned base64 image with the text request metadata for gallery persistence.
 *
 * @param createdAtMillis Time assigned to the generated image, in epoch milliseconds.
 * @return Text-to-image result retaining the submitted settings and generated bytes.
 *
 * @author Dmitriy Moroz
 */
fun Pair<TextToImagePayload, String>.mapHuggingFaceTextToImageResult(
    createdAtMillis: Long,
): AiGenerationResult {
    val (payload, base64) = this
    return AiGenerationResult(
        id = 0L,
        image = base64,
        inputImage = "",
        createdAt = createdAtMillis,
        type = AiGenerationResult.Type.TEXT_TO_IMAGE,
        denoisingStrength = 0f,
        prompt = payload.prompt,
        negativePrompt = payload.negativePrompt,
        width = payload.width,
        height = payload.height,
        samplingSteps = payload.samplingSteps,
        cfgScale = payload.cfgScale,
        restoreFaces = payload.restoreFaces,
        sampler = payload.sampler,
        seed = payload.seed,
        subSeed = payload.subSeed,
        subSeedStrength = payload.subSeedStrength,
        hidden = false,
    )
}

/**
 * Combines a returned base64 image with its source image and request metadata for gallery persistence.
 *
 * @param createdAtMillis Time assigned to the generated image, in epoch milliseconds.
 * @return Image-to-image result retaining the source image, submitted settings and generated bytes.
 *
 * @author Dmitriy Moroz
 */
fun Pair<ImageToImagePayload, String>.mapHuggingFaceImageToImageResult(
    createdAtMillis: Long,
): AiGenerationResult {
    val (payload, base64) = this
    return AiGenerationResult(
        id = 0L,
        image = base64,
        inputImage = payload.base64Image,
        createdAt = createdAtMillis,
        type = AiGenerationResult.Type.IMAGE_TO_IMAGE,
        denoisingStrength = payload.denoisingStrength,
        prompt = payload.prompt,
        negativePrompt = payload.negativePrompt,
        width = payload.width,
        height = payload.height,
        samplingSteps = payload.samplingSteps,
        cfgScale = payload.cfgScale,
        restoreFaces = payload.restoreFaces,
        sampler = payload.sampler,
        seed = payload.seed,
        subSeed = payload.subSeed,
        subSeedStrength = payload.subSeedStrength,
        hidden = false,
    )
}
